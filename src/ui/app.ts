  // ---------- live run (NDJSON stream) ----------
  function run(extra) {
    begin('Starting run');
    fetch('/api/slate', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(requestBody(extra)) })
      .then(function (res) {
        if (!res.ok) return res.json().then(function (j) { busy(false); showError(j.error || ('Request failed (' + res.status + ')')); });
        var reader = res.body.getReader(); var dec = new TextDecoder(); var buf = '';
        function pump() {
          return reader.read().then(function (r) {
            if (r.done) { busy(false); return; }
            buf += dec.decode(r.value, { stream: true });
            var lines = buf.split('\n'); buf = lines.pop();
            lines.forEach(function (l) { if (l.trim()) handle(JSON.parse(l)); });
            return pump();
          });
        }
        return pump();
      }).catch(function () { busy(false); showError('The connection dropped before the run finished. Nothing from it is shown. Try again.'); });
  }

