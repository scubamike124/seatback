  function topDestLine(net, ranked) {
    var shown = {}; ranked.slice(0, 6).forEach(function (c) { shown[c.code] = true; });
    var byCode = {}; net.rows.forEach(function (c) { byCode[c.code] = c; });
    var parts = net.topDestinations.map(function (d) {
      var why = '';
      if (d.code && shown[d.code]) why = '';
      else if (!d.code) why = 'not on your network list';
      else if (byCode[d.code] && byCode[d.code].status === 'ranked') why = 'ranked lower';
      else if (byCode[d.code] && byCode[d.code].status === 'withheld') why = 'withheld: the two readings disagree on it';
      else why = 'not in both readings';
      return d.name + (why ? ' (' + why + ')' : '');
    });
    return el('p', { class: 'hint small', text: "Qloo's raw top US destinations for this audience, before filtering to your network (so it can name cities the list above leaves out, for the reason in brackets): " + parts.join(', ') + '.' });
  }
