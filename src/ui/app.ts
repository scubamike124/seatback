      el('summary', { text: 'What this number is' }),
      el('p', { class: 'hint small', text: 'The same catalogue and passenger mix, run again with ' + short(sw.replaced) + ' replaced by another network city. A route-blind baseline changes 0 of ' + sw.total + ' by construction. ' + sw.basis + ' It counts changed picks; it does not show the new picks are better. By type: ' + sw.byDomain.map(function (d) { return d.label + ' ' + d.changed + ' of ' + d.total; }).join(', ') + '. This check made ' + sw.qlooCalls + ' extra Qloo calls' + (sw.synthetic ? ' (none in synthetic mode: the fixture answered them)' : '') + '.' })
