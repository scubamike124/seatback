  function plain(t) { return String(t == null ? '' : t).replace(/\s*\(synthetic\)/gi, ''); }
  function readingsNote(ds, r) {
    if (ds.scale === 'single-end' || (ds.picks.length > 0 && ds.picks.every(function (p) { return p.side === 'single-end'; }))) {
      var side = ds.picks[0] && ds.picks[0].rankOrigin ? r.route.origin : r.route.destination;
      return 'Only ' + plain(short(side.label)) + ' could be read for this group, so each pick shows its rank in that city and no route fit.';
    }
    if (ds.readings >= 2) return 'Scored in two independent readings per city; titles the readings disagree on are withheld.';
    if (ds.readings === 1) return 'One reading only: no consistency check for this group.';
    return '';
  }
