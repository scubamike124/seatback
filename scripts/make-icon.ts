// Generates src/ui/icon.ts: a 180x180 PNG (apple-touch-icon) drawn from the Seatback monogram path, with node:zlib only.
// No third-party assets. Output is deterministic; test/node-host.test.ts checks the committed file equals this script's output.
//   node scripts/make-icon.ts          (rewrites src/ui/icon.ts)
import { crc32, deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const N = 180, S = N / 32;
const NAVY: [number, number, number] = [0x12, 0x3a, 0x5c], WHITE: [number, number, number] = [255, 255, 255];
// The logo path in the page header: M9 22 V10 h7 a5 5 0 0 1 0 10 h-4 (32x32 units)
const pts: [number, number][] = [[9, 22], [9, 10], [16, 10]];
for (let a = -90; a <= 90; a += 6) pts.push([16 + 5 * Math.cos((a * Math.PI) / 180), 15 + 5 * Math.sin((a * Math.PI) / 180)]);
pts.push([12, 20]);
function dist(px: number, py: number): number {
  let best = Infinity;
  for (let i = 0; i < pts.length - 1; i++) {
    const [x1, y1] = pts[i]!, [x2, y2] = pts[i + 1]!;
    const dx = x2 - x1, dy = y2 - y1, t = Math.max(0, Math.min(1, ((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy)));
    best = Math.min(best, Math.hypot(px - (x1 + t * dx), py - (y1 + t * dy)));
  }
  return best;
}
export function makePng(): Buffer {
  const rows: Buffer[] = [];
  for (let y = 0; y < N; y++) {
    const row = Buffer.alloc(1 + N * 3);
    for (let x = 0; x < N; x++) {
      let cover = 0;
      for (const [ox, oy] of [[.25, .25], [.75, .25], [.25, .75], [.75, .75]]) if (dist((x + ox!) / S, (y + oy!) / S) <= 1.7) cover++;
      const k = cover / 4;
      for (let c = 0; c < 3; c++) row[1 + x * 3 + c] = Math.round(NAVY[c]! * (1 - k) + WHITE[c]! * k);
    }
    rows.push(row);
  }
  const chunk = (type: string, data: Buffer) => { const b = Buffer.concat([Buffer.from(type), data]); const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(b)); return Buffer.concat([len, b, crc]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(N, 0); ihdr.writeUInt32BE(N, 4); ihdr[8] = 8; ihdr[9] = 2;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(Buffer.concat(rows), { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
export const iconSource = () => `// GENERATED by scripts/make-icon.ts (node scripts/make-icon.ts). 180x180 PNG apple-touch-icon, Seatback monogram, no third-party assets.\nexport const ICON_PNG_BASE64 = '${makePng().toString('base64')}';\n`;
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) { writeFileSync(new URL('../src/ui/icon.ts', import.meta.url), iconSource()); console.log('wrote src/ui/icon.ts'); }
